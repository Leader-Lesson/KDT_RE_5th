# -------------------------------
# 문자열 그대로 입력 시
# -------------------------------
# 과일1, 과일2, 과일3 = input()
# "수박, 사과, 포도"


# -------------------------------
# 문자열을 쪼개주는 함수: split
# -------------------------------
# split은 구분자를 기준으로 문자열을 쪼개서 리스트를 반환함
# 구분자의 기본값은 공백
# 예시:
# 과일1, 과일2, 과일3 = "수박 사과 참외".split()
# print(과일1)
# print(과일2)
# print(과일3)

# input에 적용
과일1, 과일2, 과일3 = input().split()
print(과일1)
print(과일2)
print(과일3)


# -------------------------------
# 다른 구분자 사용 예시
# -------------------------------
쪼갠결과 = "코딩은-즐거워-하하하".split("-")
print(쪼갠결과)


# -------------------------------
# 여러 자료 입력하기 (Review)
# -------------------------------
# 과일1, 과일2, 과일3 = "사과", "참외", "수박"
