# =========================================
# 04. 사용자 입력 (input)
# - input 함수 : 콘솔을 통해 사용자로부터 문자열 형태의 입력을 받는 함수 
#   - input을 통해 받은 입력은 항상 문자열로 입력됨
# =========================================


# -------------------------------
# input 함수 사용법
# -------------------------------
# my_input = input()
# input을 통해 받은 입력 → 문자열
# 숫자로 활용할 시 '형변환'을 해야 함!!
# 정수 계산 시 정수형으로 변환
a = int(input())
b = int(input())
print(a + b)


# -------------------------------
# 실수 계산을 하려면 실수형으로 변환
# -------------------------------
c = float(input())
d = float(input())
print(c + d)


# -------------------------------
# input의 입력에 대한 설명문 추가
# -------------------------------
name = input("이름을 입력하세요: ")
print(f"제이름은 {name}입니다.")


# -------------------------------
# 여러 자료 입력하기
# -------------------------------
국어, 영어, 수학, 사회 = 100, 80, 90, 85
