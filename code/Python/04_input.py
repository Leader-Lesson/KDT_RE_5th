# -------------------------------
# 실습6
# 년, 월, 일과 시, 분, 초를 입력받아 형식에 맞게 출력
# -------------------------------
year, month, day = input("년, 월, 일을 입력해주세요. '.'으로 구분해주세요: ").split(".")
hour, minute, second = input("시, 분, 초를 입력해주세요. ':'으로 구분해주세요: ").split(":")

print(f"""🤗RE3의 개강일은 {year}년 {month}월 {day}일
{hour}시 {minute}분 {second}초입니다.""")
